# Here are the **most commonly used Python built-in functions** that every programmer uses regularly:

# ---

#**Input & Output**

# 1. `print()` – Displays output.
# 2. `input()` – Takes user input (as a string).

# ---

#**Type & Conversion**

# 3. `type()` – Returns the data type.
# 4. `int()`, `float()`, `str()`, `bool()` – Type conversion.
# 5. `len()` – Returns length of string, list, tuple, etc.
# 6. `id()` – Returns memory address.

# ---

# **Mathematical & Number Handling**

# 7. `abs()` – Absolute value.
# 8. `round()` – Rounds a number.
# 9. `sum()` – Sums elements in an iterable.
# 10. `min()`, `max()` – Returns smallest/largest value.
# 11. `pow(x, y)` – Returns x^y.
# 12. `divmod(x, y)` – Returns (quotient, remainder).

# ---

#  **Sequence & Collection Handling**

# 13. `sorted()` – Sorts an iterable.
# 14. `reversed()` – Reverses an iterable.
# 15. `enumerate()` – Adds index to iterable in loop.
# 16. `zip()` – Combines multiple iterables.
# 17. `map()` – Applies function to each item.
# 18. `filter()` – Filters items using a condition.
# 19. `range()` – Generates a sequence of numbers.

# ---

# *String Related**

# 20. `str.upper()`, `str.lower()`, `str.title()` – Case changes.
# 21. `str.split()`, `str.join()` – Splitting & joining strings.
# 22. `str.strip()` – Removes whitespace.
# 23. `str.replace()` – Replace substring.

# ---

# **File Handling**

# 24. `open()` – Opens a file.
# 25. `read(ansh vishnubhai patel )`, `write()`, `close()` – File operations.

# ---

# **Utility & Checks**

# 26. `isinstance()` – Checks object type.
# 27. `dir()` – Lists attributes & methods.
# 28. `help()` – Documentation for functions.
# 29. `any()`, `all()` – Checks conditions in iterables.
# 30. `eval()` – Evaluates Python expression (use with caution).

