# **Common Escape Characters in Python**

# | Escape Character | Meaning                           | Example               | Output               |
# | ---------------- | --------------------------------- | --------------------- | -------------------- |
# | `\'`             | Single quote                      | `'It\'s Python'`      | `It's Python`        |
# | `\"`             | Double quote                      | `"He said \"Hello\""` | `He said "Hello"`    |
# | `\\`             | Backslash                         | `"C:\\Users\\Name"`   | `C:\Users\Name`      |
# | `\n`             | New line                          | `"Hello\nWorld"`      | `Hello`<br>`World`   |
# | `\t`             | Tab space                         | `"Hello\tWorld"`      | `Hello    World`     |
# | `\r`             | Carriage return                   | `"Hello\rWorld"`      | `World`              |
# | `\b`             | Backspace (removes previous char) | `"Hello\bWorld"`      | `HellWorld`          |
# | `\f`             | Form feed (page break)            | `"Hello\fWorld"`      | `Hello`<form>`World` |
# | `\v`             | Vertical tab
# | `"Hello\vWorld"`      | `Hello`<vtab>`World` |













