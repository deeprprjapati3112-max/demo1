name = "deep"

print(len(name)) # for length
print(name.upper())  # for upper case
print(name.lower())  # for lower case
print(name.capitalize())  # for capitalizing the first letter
print(name.startswith("d"))  # for checking if the string starts with a specific character
print(name.endswith("p"))  # for checking if the string ends with a specific character
print(name.find("p"))  # for finding the index of a specific character  